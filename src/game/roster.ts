import type { Look } from './Rig';

export interface Stats {
  power: number; // 1-10
  speed: number;
  technique: number;
  toughness: number;
}

export interface Moveset {
  strike: string; // standing attack + direction
  running: string; // running attack
  grappleA: string; // grapple + attack
  grappleADir: string; // grapple + direction + attack
  grappleG: string; // grapple + grab
  grappleGDir: string; // grapple + direction + grab
  behindA: string;
  behindG: string;
  runningGrab: string;
  counterWhip: string; // grab an opponent running at you
  submission: string; // on downed opponent
  finisher: string;
  finisherName: string;
  dive: 'splash' | 'elbow' | 'legdrop';
}

export interface Wrestler {
  id: string;
  name: string;
  nick: string;
  hometown: string;
  weight: string;
  look: Look;
  stats: Stats;
  moves: Moveset;
  colour: string;
  style: 'brawler' | 'highflyer' | 'technician' | 'powerhouse' | 'hardcore' | 'showman';
}

